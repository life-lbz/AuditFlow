POLICY_GENERAL = PolicySpec(
    policy_id="policy_general",
    title="费用报销总则",
    version="3.0",
    effective_date="2026-01-01",
    category="general",
    markdown="""# 费用报销总则（v3.0）

## 一、基本原则

所有报销必须真实、必要、合规，且与实际业务相符。
报销人对其提交材料的真实性负责，虚假报销将按公司纪律处理。
同一笔费用不得重复报销。系统会按发票号与金额自动比对历史案件。

## 二、发票要求

报销必须提供合法有效的增值税发票或财政票据。
发票必需字段包括：发票号码、开票日期、金额、销售方名称。
发票抬头必须为公司全称，个人抬头发票不予报销。
发票号码在同一自然年度内不得重复使用。

## 三、审批规则

单笔报销金额超过 1000 元需提供部门负责人审批记录。
差旅类报销无论金额大小均需提供出差审批邮件。
审批记录应与报销事由、金额、时间相匹配。

## 四、报销时限

费用发生后 60 个自然日内提交报销，超期需说明原因。
跨年度费用不得在次年报销，特殊情况需财务总监审批。

## 五、提交要求

报销人需上传发票、审批邮件与银行流水等支撑材料。
材料不完整的案件将被退回补件，补件后重新进入审核流程。
""",
)

POLICY_ANTI_FRAUD = PolicySpec(
    policy_id="policy_anti_fraud",
    title="费用报销反舞弊规定",
    version="1.1",
    effective_date="2026-01-01",
    category="general",
    markdown="""# 费用报销反舞弊规定（v1.1）

## 一、舞弊行为认定

以下行为认定为报销舞弊：伪造或变造发票、重复报销同一笔费用、
拆分发票规避审批额度、虚构出差行程、串通供应商虚开发票。

## 二、异常供应商

与公司无历史合作记录且短期内多次出现的供应商，需人工核验资质。
鑫鑫贸易、宏达咨询等列入观察名单的供应商，其发票需二级审核。
供应商名称与发票税号不匹配的，一律转人工审核。

## 三、异常模式识别

同一发票号在不同案件中出现，判定为重复报销，直接转人工审核。
发票金额与银行流水金额差异超过 1% 的，判定为金额异常，转人工审核。
同一员工在同一自然月内提交超过 8 笔报销的，触发合规抽查。

## 四、处理流程

发现舞弊线索后，审核员应暂停付款并请报销人补充说明。
确认舞弊的，案件驳回并转入纪律处理流程。
审核员对高风险案件拥有最终否决权。
""",
)

